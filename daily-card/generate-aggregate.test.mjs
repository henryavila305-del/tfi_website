import assert from 'node:assert/strict';
import {generateAuditedPublicSnapshot} from './generate-aggregate.mjs';
import {safePublicRecordSnapshot} from './public-record-adapter.mjs';
const audit={baselineWorkbook:'TFI_Record_Tracker_Updated_Nov8.xlsx',reconciled:true,approved:true};
const islanders={id:'nov9-islanders',game_date:'2026-11-09',category:'Main Premium',status:'loss',auditMatched:true};
const input={picks:[islanders],throughDate:'2026-11-09',audit};
assert.throws(()=>generateAuditedPublicSnapshot({...input,audit:{...audit,approved:false}}),/approval required/);
const snapshot=generateAuditedPublicSnapshot(input);
assert.deepEqual(snapshot.records['Premium / Max Bet'],{wins:64,losses:33,pushes:0});
assert.equal(safePublicRecordSnapshot(snapshot)['Premium / Max Bet'].winRate,'65.98');
assert(!JSON.stringify(snapshot).includes('Islanders'));
assert(!JSON.stringify(snapshot).includes('Main Premium'));
assert.throws(()=>generateAuditedPublicSnapshot({...input,picks:[islanders,islanders]}),/Duplicate/);
assert.throws(()=>generateAuditedPublicSnapshot({...input,picks:[{...islanders,game_date:'2026-11-03'}]}),/Outside/);
assert.throws(()=>generateAuditedPublicSnapshot({...input,picks:[{...islanders,auditMatched:false}]}),/individually audited/);
const featured=generateAuditedPublicSnapshot({...input,picks:[islanders,{id:'synthetic-michigan',game_date:'2026-11-09',category:'NCAAB Premium',status:'win',auditMatched:true,featuredPlayOfDay:true}]});
assert.deepEqual(featured.records['Play of the Day'],{wins:25,losses:31,pushes:2});
assert.deepEqual(featured.records['Premium / Max Bet'],{wins:64,losses:33,pushes:0});
console.log('PASS: baseline cutoff, audited additions, category segregation, featured Play of the Day and no private pick leakage');
